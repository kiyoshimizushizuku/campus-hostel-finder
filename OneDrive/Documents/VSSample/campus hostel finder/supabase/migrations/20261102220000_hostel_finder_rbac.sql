create or replace function public.admin_set_status(uid uuid, s text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;
  if uid = auth.uid() then
    raise exception 'Admins cannot suspend their own account';
  end if;
  if s not in ('active', 'suspended') then
    raise exception 'Invalid account status';
  end if;
  update public.profiles set status = s where id = uid and role <> 'ADMIN';
  if not found then
    raise exception 'User not found or cannot be changed';
  end if;
end;
$$;

create or replace function public.admin_update_profile_basics(
  target_user_id uuid,
  user_name text,
  contact_no text,
  contact_email text,
  university_id bigint,
  department text,
  bio text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_role text;
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;
