create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  role text not null check (role in ('STUDENT', 'LANDLORD', 'ADMIN')),
  status text not null default 'active' check (status in ('active', 'suspended')),
  created_at timestamptz not null default now()
);

create table if not exists public.universities (
  id bigint generated by default as identity primary key,
  name text not null unique,
  short_name text,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180)
);

create table if not exists public.student_profiles (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  name text,
  contact_email text,
  contact_no text,
  university_id bigint references public.universities (id) on delete set null,
  target_university_id bigint references public.universities (id) on delete set null,
  target_lat double precision check (target_lat is null or target_lat between -90 and 90),
  target_lng double precision check (target_lng is null or target_lng between -180 and 180),
  department text,
  blood_group text check (blood_group is null or blood_group in ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
  guardian_name text,
  guardian_contact text,
  emergency_info text,
  staying_lat double precision check (staying_lat is null or staying_lat between -90 and 90),
  staying_lng double precision check (staying_lng is null or staying_lng between -180 and 180),
  profile_pic_url text,
  verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((staying_lat is null) = (staying_lng is null)),
  check ((target_lat is null) = (target_lng is null))
);

