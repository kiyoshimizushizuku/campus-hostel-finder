create table if not exists public.hostels (
  id uuid primary key default gen_random_uuid(),
  landlord_id uuid not null references public.profiles (id) on delete cascade,
  house_name text not null,
  property_type text not null default 'Mess',
  address text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  monthly_rent numeric(12, 2) not null default 0 check (monthly_rent >= 0),
  total_rooms integer check (total_rooms is null or total_rooms >= 0),
  vacancy_count integer not null default 0 check (vacancy_count >= 0),
  electricity_bill_type text not null default 'fixed' check (electricity_bill_type in ('fixed', 'meter')),
  electricity_bill numeric(12, 2) not null default 0 check (electricity_bill >= 0),
  water_bill numeric(12, 2) not null default 0 check (water_bill >= 0),
  trash_bill numeric(12, 2) not null default 0 check (trash_bill >= 0),
  photos text[] not null default '{}',
  room_details jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (total_rooms is null or vacancy_count <= total_rooms)
);

