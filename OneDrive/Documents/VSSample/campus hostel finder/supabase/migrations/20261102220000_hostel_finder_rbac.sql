create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  account_role text;
  account_name text;
begin
  account_role := case
    when new.raw_user_meta_data ->> 'role' = 'LANDLORD' then 'LANDLORD'
    else 'STUDENT'
  end;
  account_name := nullif(trim(new.raw_user_meta_data ->> 'name'), '');

  insert into public.profiles (id, email, role)
  values (new.id, lower(new.email), account_role)
  on conflict (id) do update set email = excluded.email;

  if account_role = 'STUDENT' then
    insert into public.student_profiles (user_id, name)
    values (new.id, account_name)
    on conflict (user_id) do nothing;
  else
    insert into public.landlord_profiles (user_id, name)
    values (new.id, account_name)
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

