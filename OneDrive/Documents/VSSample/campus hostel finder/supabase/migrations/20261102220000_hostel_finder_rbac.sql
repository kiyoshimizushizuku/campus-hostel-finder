create or replace function public.hostels_near_university(uni_id bigint, radius_km double precision default 10)
returns table (
  id uuid,
  landlord_id uuid,
  house_name text,
  address text,
  monthly_rent numeric,
  vacancy_count integer,
  electricity_bill numeric,
  water_bill numeric,
  trash_bill numeric,
  distance_km double precision,
  lat double precision,
  lng double precision
)
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
begin
  if not public.has_active_role('STUDENT') then
    raise exception 'An active student account is required';
  end if;
  if radius_km is null or radius_km < 0 or radius_km > 100 then
    raise exception 'Radius must be between 0 and 100 km';
  end if;
  if not exists (select 1 from public.universities u where u.id = uni_id) then
    raise exception 'University not found';
  end if;

  return query
  select h.id, h.landlord_id, h.house_name, h.address, h.monthly_rent,
         h.vacancy_count, h.electricity_bill, h.water_bill, h.trash_bill,
         distance.km, h.lat, h.lng
  from public.hostels h
  cross join public.universities u
  cross join lateral (
    select 6371 * 2 * asin(sqrt(
      power(sin(radians(h.lat - u.lat) / 2), 2)
      + cos(radians(u.lat)) * cos(radians(h.lat))
      * power(sin(radians(h.lng - u.lng) / 2), 2)
    )) as km
  ) distance
  where u.id = uni_id
    and h.status = 'approved'
    and h.vacancy_count > 0
    and distance.km <= radius_km
  order by distance.km;
end;
$$;

